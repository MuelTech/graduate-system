import { Buffer } from "buffer";
import { createHash } from "crypto";
import fsp from "fs/promises";
import path from "path";
import zlib from "zlib";
import { PDFDocument, StandardFonts, rgb } from "pdf-lib";
import { PRIVATE_UPLOAD_ROOT, STORAGE_CONFIG } from "../src/utils/file.utils";

export type SeedPdfNamespace = "cor" | "manuscripts" | "evidence" | "root";

export interface SyntheticPdfInput {
  namespace: SeedPdfNamespace;
  filename: string;
  originalFilename: string;
  documentCategory: string;
  subjectName: string;
  identifierLabel: string;
  identifierValue: string;
  programName: string;
  details: Array<{ label: string; value: string }>;
  notes?: string;
}

export interface SyntheticPdfArtifact {
  filePath: string;
  storageKey: string | null;
  storageProvider: string;
  originalFilename: string;
  verifiedMimeType: "application/pdf";
  detectedMimeType: "application/pdf";
  sizeBytes: number;
  checksum: string;
  checksumAlgorithm: "sha256";
}

function wrapText(text: string, maxChars: number): string[] {
  const words = text.trim().split(/\s+/);
  const lines: string[] = [];
  let current = "";
  for (const word of words) {
    if (!current) {
      current = word;
    } else if (current.length + 1 + word.length <= maxChars) {
      current += ` ${word}`;
    } else {
      lines.push(current);
      current = word;
    }
  }
  if (current) lines.push(current);
  return lines;
}

/**
 * Generates an authentic-looking multi-line EARIST Graduate School synthetic PDF
 * inside PRIVATE_UPLOAD_ROOT and returns full DL-1/DL-2 storage metadata.
 */
export async function ensureSyntheticPdf(
  input: SyntheticPdfInput,
): Promise<SyntheticPdfArtifact> {
  const pdfDoc = await PDFDocument.create();
  const page = pdfDoc.addPage([612, 792]); // US Letter portrait
  const fontBold = await pdfDoc.embedFont(StandardFonts.HelveticaBold);
  const fontRegular = await pdfDoc.embedFont(StandardFonts.Helvetica);

  const maroon = rgb(0.55, 0.08, 0.12);
  const charcoal = rgb(0.14, 0.16, 0.2);
  const muted = rgb(0.42, 0.45, 0.5);
  const border = rgb(0.84, 0.86, 0.9);
  const tintBg = rgb(0.98, 0.96, 0.95);

  // Header band
  page.drawRectangle({
    x: 48,
    y: 686,
    width: 516,
    height: 62,
    color: tintBg,
    borderColor: maroon,
    borderWidth: 1.2,
  });

  page.drawText(
    'EULOGIO "AMANG" RODRIGUEZ INSTITUTE OF SCIENCE AND TECHNOLOGY',
    { x: 64, y: 726, size: 11, font: fontBold, color: maroon },
  );
  page.drawText("Nagtahan, Sampaloc, Manila | Graduate School (GS-IS)", {
    x: 64,
    y: 710,
    size: 9.5,
    font: fontRegular,
    color: charcoal,
  });
  page.drawText(`Document Category: ${input.documentCategory}`, {
    x: 64,
    y: 695,
    size: 9,
    font: fontBold,
    color: muted,
  });

  // Title block
  let y = 650;
  page.drawText(input.documentCategory.toUpperCase(), {
    x: 48,
    y,
    size: 15,
    font: fontBold,
    color: charcoal,
  });
  y -= 16;
  page.drawLine({
    start: { x: 48, y },
    end: { x: 564, y },
    thickness: 1,
    color: border,
  });

  const rows: Array<{ label: string; value: string }> = [
    { label: "Name", value: input.subjectName },
    { label: input.identifierLabel, value: input.identifierValue },
    { label: "Graduate Program", value: input.programName },
    ...input.details,
    { label: "Original Filename", value: input.originalFilename },
  ];

  y -= 28;
  for (const row of rows) {
    page.drawText(`${row.label}:`, {
      x: 48,
      y,
      size: 10,
      font: fontBold,
      color: muted,
    });
    const wrapped = wrapText(row.value || "N/A", 62);
    for (let i = 0; i < wrapped.length; i++) {
      page.drawText(wrapped[i], {
        x: 185,
        y: y - i * 14,
        size: 10.5,
        font: fontRegular,
        color: charcoal,
      });
    }
    y -= Math.max(22, wrapped.length * 14 + 8);
  }

  y -= 10;
  page.drawRectangle({
    x: 48,
    y: y - 95,
    width: 516,
    height: 105,
    borderColor: border,
    borderWidth: 1,
  });

  const bodyLines = wrapText(
    input.notes ??
      "This synthetic PDF file was generated by the EARIST Graduate School Information System (GS-IS) database seed so uploaded requirement previews, official workflows, and document verification paths operate on real PDF binaries without broken local file references.",
    82,
  );
  page.drawText("DOCUMENT SUMMARY", {
    x: 62,
    y: y - 10,
    size: 9.5,
    font: fontBold,
    color: maroon,
  });
  for (let i = 0; i < bodyLines.length && i < 5; i++) {
    page.drawText(bodyLines[i], {
      x: 62,
      y: y - 28 - i * 14,
      size: 9.5,
      font: fontRegular,
      color: charcoal,
    });
  }

  // Footer
  page.drawLine({
    start: { x: 48, y: 74 },
    end: { x: 564, y: 74 },
    thickness: 0.75,
    color: border,
  });
  page.drawText(
    "EARIST GS-IS | Managed Private Document Storage | Synthetic QA Record",
    { x: 48, y: 58, size: 8.5, font: fontRegular, color: muted },
  );

  const bytes = Buffer.from(await pdfDoc.save());
  const checksum = createHash("sha256").update(bytes).digest("hex");

  const isRoot = input.namespace === "root";
  const diskDir = isRoot
    ? PRIVATE_UPLOAD_ROOT
    : path.join(PRIVATE_UPLOAD_ROOT, input.namespace);
  await fsp.mkdir(diskDir, { recursive: true });
  const diskPath = path.join(diskDir, input.filename);
  await fsp.writeFile(diskPath, bytes);

  return {
    filePath: isRoot ? `uploads/${input.filename}` : diskPath,
    storageKey: isRoot ? null : `${input.namespace}/${input.filename}`,
    storageProvider: STORAGE_CONFIG.provider,
    originalFilename: input.originalFilename,
    verifiedMimeType: "application/pdf",
    detectedMimeType: "application/pdf",
    sizeBytes: bytes.length,
    checksum,
    checksumAlgorithm: "sha256",
  };
}

let cachedSignatureDataUrl: string | null = null;

function crc32(buf: Buffer): number {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) {
    c ^= buf[i];
    for (let k = 0; k < 8; k++) {
      c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    }
  }
  return (c ^ 0xffffffff) >>> 0;
}

function pngChunk(type: string, data: Buffer): Buffer {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length, 0);
  const typeBuf = Buffer.from(type, "ascii");
  const crcBuf = Buffer.alloc(4);
  crcBuf.writeUInt32BE(crc32(Buffer.concat([typeBuf, data])), 0);
  return Buffer.concat([len, typeBuf, data, crcBuf]);
}

/**
 * Generates a valid 160x48 RGBA PNG handwritten-style signature data URL
 * compatible with both browser <img> previews and pdf-lib embedPng().
 */
export function getSyntheticSignatureDataUrl(): string {
  if (cachedSignatureDataUrl) return cachedSignatureDataUrl;

  const width = 160;
  const height = 48;
  const raw = Buffer.alloc(height * (1 + width * 4)); // filter byte + RGBA

  const plotDot = (cx: number, cy: number) => {
    for (let dy = -1; dy <= 1; dy++) {
      for (let dx = -1; dx <= 1; dx++) {
        const px = Math.round(cx) + dx;
        const py = Math.round(cy) + dy;
        if (px < 0 || px >= width || py < 0 || py >= height) continue;
        const offset = py * (1 + width * 4) + 1 + px * 4;
        raw[offset] = 20;
        raw[offset + 1] = 32;
        raw[offset + 2] = 68;
        raw[offset + 3] = 255;
      }
    }
  };

  for (let t = 0; t <= 220; t++) {
    const u = t / 220;
    const x = 14 + u * 130;
    const y =
      26 +
      Math.sin(u * Math.PI * 5) * 9 * (1 - 0.35 * u) -
      Math.cos(u * Math.PI * 2) * 3;
    plotDot(x, y);
  }
  // Underline flourish
  for (let x = 22; x <= 136; x++) {
    plotDot(x, 38 - Math.sin(((x - 22) / 114) * Math.PI) * 2);
  }

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(width, 0);
  ihdr.writeUInt32BE(height, 4);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 6; // RGBA
  ihdr[10] = 0;
  ihdr[11] = 0;
  ihdr[12] = 0;

  const idat = zlib.deflateSync(raw);
  const png = Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    pngChunk("IHDR", ihdr),
    pngChunk("IDAT", idat),
    pngChunk("IEND", Buffer.alloc(0)),
  ]);

  cachedSignatureDataUrl = `data:image/png;base64,${png.toString("base64")}`;
  return cachedSignatureDataUrl;
}
